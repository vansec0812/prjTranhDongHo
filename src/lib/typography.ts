const phrasePattern = new RegExp(
  `(?<![\\p{L}\\p{M}\\p{N}_])(?:${compounds
    .sort((a, b) => b.length - a.length)
    .map((phrase) => phrase.replaceAll(" ", "[ \\u00a0\\t]+"))
    .join("|")})(?![\\p{L}\\p{M}\\p{N}_])`,
  "giu",
);

export function keepCompoundWords(value: string) {
  return value.replace(phrasePattern, (phrase) =>
    phrase.replace(/[ \t]+/g, "\u00a0"),
  );
}
